// Package potgen extracts the catalog's messages from the Go source: every string literal passed
// to i18n.T, i18n.N or i18n.M. `make po` writes them to locales/; the glyph test reads them too.
package potgen

import (
	"bytes"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strconv"
	"strings"
)

// Message is one catalog entry.
type Message struct {
	ID, Plural string
	Refs       []string // files, relative to the root
}

// Extract walks the non-test .go files under root/dirs and returns their messages, in source order.
func Extract(root string, dirs ...string) ([]Message, error) {
	var msgs []Message
	index := map[string]int{}
	fset := token.NewFileSet()
	for _, d := range dirs {
		err := filepath.WalkDir(filepath.Join(root, d), func(p string, e fs.DirEntry, err error) error {
			if err != nil || e.IsDir() || !strings.HasSuffix(p, ".go") || strings.HasSuffix(p, "_test.go") {
				return err
			}
			f, err := parser.ParseFile(fset, p, nil, parser.SkipObjectResolution)
			if err != nil {
				return err
			}
			rel, _ := filepath.Rel(root, p)
			ast.Inspect(f, func(n ast.Node) bool {
				call, ok := n.(*ast.CallExpr)
				if !ok {
					return true
				}
				sel, ok := call.Fun.(*ast.SelectorExpr)
				if !ok {
					return true
				}
				if x, ok := sel.X.(*ast.Ident); !ok || x.Name != "i18n" {
					return true
				}
				var id, plural string
				switch sel.Sel.Name {
				case "T", "M":
					if len(call.Args) < 1 {
						return true
					}
					if id, ok = literal(call.Args[0]); !ok {
						return true // a variable: translated from data marked with M elsewhere
					}
				case "N":
					if len(call.Args) < 3 {
						return true
					}
					a, ok1 := literal(call.Args[0])
					b, ok2 := literal(call.Args[1])
					if !ok1 || !ok2 {
						return true
					}
					id, plural = a, b
				default:
					return true
				}
				ref := filepath.ToSlash(rel) // files only: line numbers would make every edit touch the catalogs
				if i, seen := index[id]; seen {
					if !slices.Contains(msgs[i].Refs, ref) {
						msgs[i].Refs = append(msgs[i].Refs, ref)
					}
					if msgs[i].Plural == "" {
						msgs[i].Plural = plural
					}
					return true
				}
				index[id] = len(msgs)
				msgs = append(msgs, Message{ID: id, Plural: plural, Refs: []string{ref}})
				return true
			})
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	return msgs, nil
}

// literal reads a string literal, or a + concatenation of them.
func literal(e ast.Expr) (string, bool) {
	switch v := e.(type) {
	case *ast.BasicLit:
		if v.Kind != token.STRING {
			return "", false
		}
		s, err := strconv.Unquote(v.Value)
		return s, err == nil
	case *ast.BinaryExpr:
		if v.Op != token.ADD {
			return "", false
		}
		a, ok1 := literal(v.X)
		b, ok2 := literal(v.Y)
		return a + b, ok1 && ok2
	case *ast.ParenExpr:
		return literal(v.X)
	}
	return "", false
}

// Write renders a catalog: the template when lang is "", else that language's file with empty
// msgstrs (English is the source language).
func Write(msgs []Message, lang string) []byte {
	var b bytes.Buffer
	b.WriteString("# boot-live messages. Generated by `make po` from the Go source; edit translations only.\n")
	b.WriteString("msgid \"\"\nmsgstr \"\"\n")
	b.WriteString(`"Project-Id-Version: boot-live\n"` + "\n")
	b.WriteString(`"MIME-Version: 1.0\n"` + "\n")
	b.WriteString(`"Content-Type: text/plain; charset=UTF-8\n"` + "\n")
	b.WriteString(`"Content-Transfer-Encoding: 8bit\n"` + "\n")
	if lang != "" {
		b.WriteString(`"Language: ` + lang + `\n"` + "\n")
	}
	b.WriteString(`"Plural-Forms: nplurals=2; plural=(n != 1);\n"` + "\n")
	for _, m := range msgs {
		b.WriteByte('\n')
		refs := append([]string(nil), m.Refs...)
		sort.Strings(refs)
		b.WriteString("#: " + strings.Join(refs, " ") + "\n")
		if fmtVerb.MatchString(m.ID) {
			b.WriteString("#, c-format\n")
		}
		b.WriteString("msgid " + quote(m.ID) + "\n")
		if m.Plural != "" {
			b.WriteString("msgid_plural " + quote(m.Plural) + "\n")
			b.WriteString("msgstr[0] \"\"\nmsgstr[1] \"\"\n")
		} else {
			b.WriteString("msgstr \"\"\n")
		}
	}
	return b.Bytes()
}

var fmtVerb = regexp.MustCompile(`%(\[\d+\])?[-+# 0]*\d*(\.\d+)?[vdsqfxXegc%]`)

func quote(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "\t", `\t`)
	return `"` + r.Replace(s) + `"`
}

// Msgstrs reads every translated string (msgstr lines) of a .po file, for the glyph check.
func Msgstrs(path string) ([]string, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var out []string
	var cur *strings.Builder
	for _, line := range strings.Split(string(b), "\n") {
		line = strings.TrimSpace(line)
		switch {
		case strings.HasPrefix(line, "msgstr"):
			if cur != nil {
				out = append(out, cur.String())
			}
			cur = &strings.Builder{}
			if i := strings.IndexByte(line, '"'); i >= 0 {
				s, _ := strconv.Unquote(line[i:])
				cur.WriteString(s)
			}
		case strings.HasPrefix(line, `"`) && cur != nil:
			s, _ := strconv.Unquote(line)
			cur.WriteString(s)
		default:
			if cur != nil {
				out = append(out, cur.String())
				cur = nil
			}
		}
	}
	if cur != nil {
		out = append(out, cur.String())
	}
	return out, nil
}
